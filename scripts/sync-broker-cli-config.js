#!/usr/bin/env node
'use strict';

const fs = require('fs');
const path = require('path');
const flags2env = require('@oresoftware/f2e');

const root = path.resolve(__dirname, '..');
const configPath = path.join(root, '.cli-flags.toml');
const generate = language => flags2env.generateTypes(language, {
  configPath,
  typeName: 'BrokerCliConfig',
});
const withFinalNewline = value => value.endsWith('\n') ? value : `${value}\n`;
const schema = JSON.parse(generate('jsonschema'));
if (schema.required.length > 0) {
  throw new Error(
    `live-mutex CLI flags must not declare defaults: ${schema.required.join(', ')}. ` +
    'flags2env parse output includes defaults, which would override process environment values before coerce().'
  );
}
const keysForType = type => Object.entries(schema.properties)
  .filter(([, property]) => property.type === type)
  .map(([key]) => `  ${JSON.stringify(key)},`)
  .join('\n');
const coercionMetadata = [
  '/* Generated by flags2env from .cli-flags.toml. Do not edit. */',
  '',
  'export const BROKER_CLI_BOOLEAN_ENV_KEYS = [',
  keysForType('boolean'),
  '] as const;',
  '',
  'export const BROKER_CLI_INTEGER_ENV_KEYS = [',
  keysForType('integer'),
  '] as const;',
  '',
].join('\n');
const targets = [
  {
    relativePath: 'src/generated/broker-cli-config.ts',
    expected: withFinalNewline(generate('typescript')),
  },
  {
    relativePath: 'src/generated/broker-cli-config-metadata.ts',
    expected: coercionMetadata,
  },
].map(target => ({
  ...target,
  generatedPath: path.join(root, target.relativePath),
}));
const mode = process.argv[2] || '--check';

if (mode === '--write') {
  for (const target of targets) {
    fs.mkdirSync(path.dirname(target.generatedPath), {recursive: true});
    fs.writeFileSync(target.generatedPath, target.expected);
    console.log(`updated ${target.relativePath}`);
  }
  process.exit(0);
}

if (mode !== '--check') {
  console.error('usage: node scripts/sync-broker-cli-config.js [--check|--write]');
  process.exit(2);
}

let stale = false;
for (const target of targets) {
  let actual = '';
  try {
    actual = fs.readFileSync(target.generatedPath, 'utf8');
  } catch (error) {
    if (error && error.code !== 'ENOENT') {
      throw error;
    }
  }

  if (actual !== target.expected) {
    stale = true;
    console.error(
      `${target.relativePath} is stale; run npm run generate:cli-types and commit the result.`
    );
  }
}

if (stale) {
  process.exit(1);
}

console.log('generated broker CLI interface and metadata match .cli-flags.toml');
